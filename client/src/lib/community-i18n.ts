const dict: Record<SocialLocale, Record<keyof typeof tr, string>> = { tr, en };

export type I18nKey = keyof typeof tr;

export function translate(locale: SocialLocale, key: I18nKey, vars?: Record<string, string | number>): string {
  let text = dict[locale]?.[key] || dict.tr[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function forumTagLabel(locale: SocialLocale, tag: string): string {
  const map: Record<string, I18nKey> = {
    Sohbet: "tagChat",
    Bakım: "tagCare",
    Sağlık: "tagHealth",
    Kulüp: "tagClub",
    Chat: "tagChat",
    Grooming: "tagCare",
    Health: "tagHealth",
    Club: "tagClub",
  };
  const key = map[tag];
  return key ? translate(locale, key) : tag;
}

export function notificationText(locale: SocialLocale, kind: string, actorName: string, fallback: string): string {
  const keys: Record<string, I18nKey> = {
    follow: "notifFollow",
    comment: "notifComment",
    like: "notifLike",
    reply: "notifReply",
  };
  const key = keys[kind];
  if (!key) return fallback;
  return translate(locale, key, { name: actorName });
}

export function useCommunityI18n() {
  const { me } = useSocialAuth();
  const locale: SocialLocale = me?.locale === "en" ? "en" : "tr";
  const t = (key: I18nKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
  const timeAgo = (iso: string) => formatTimeAgo(iso, Date.now(), locale);
  return { locale, t, timeAgo };
}
